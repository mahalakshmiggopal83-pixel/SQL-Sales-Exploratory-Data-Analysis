-- =========================================
-- 5. MAGNITUDE ANALYSIS
-- =========================================

-- Find the total number customers by countries
SELECT
Country,
COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY Country
ORDER BY total_customers DESC

-- Find the total number customers by gender
SELECT
Gender,
COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY Gender
ORDER BY total_customers DESC

-- Find the total products by category
SELECT
Category,
COUNT(product_key) AS total_products
FROM gold.dim_products
GROUP BY Category
ORDER BY total_products DESC

-- what is the average costs in each category
SELECT
Category,
AVG(cost) AS avg_costs
FROM gold.dim_products
GROUP BY Category
ORDER BY avg_costs DESC

-- what is the total revenue generated for each category
SELECT
p.category,
SUM(f.sales_amount) total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON p.product_key = f.product_key GROUP BY p.category
ORDER BY total_revenue DESC

-- what is the total revenue generated by each customers
SELECT
c.customer_key,
c.first_name,
c.last_name,
SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY
c.customer_key,
c.first_name,
c.last_name
ORDER BY total_revenue DESC

-- what is the distribution of sold items across countries
SELECT
c.country,
SUM(f.quantity) AS total_sold_items
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY
c.country
ORDER BY total_sold_items DESC

-- =========================================
-- 6. RANKING ANALYSIS
-- =========================================

-- which 5 products generate the highest revenue
SELECT
p.product_name,
SUM(f.quantity) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON p.product_key = f.product_key
GROUP BY
p.product_name
ORDER BY total_revenue DESC

-- what are the 5 worst performing products in item of sales
SELECT
p.product_name,
SUM(f.quantity) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p
ON p.product_key = f.product_key
GROUP BY
p.product_name
ORDER BY total_revenue 

-- Find the top 10 customers who have generated the highest revenue
SELECT TOP 10
c.customer_key,
c.first_name,
c.last_name,
SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY
c.customer_key,
c.first_name,
c.last_name
ORDER BY total_revenue DESC

-- Find the top 3 customers with the fewest orders placed
SELECT TOP 3
c.customer_key,
c.first_name,
c.last_name,
COUNT(DISTINCT order_number) AS total_orders
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c
ON c.customer_key = f.customer_key
GROUP BY
c.customer_key,
c.first_name,
c.last_name
ORDER BY total_orders

